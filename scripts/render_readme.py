"""Render README.md from `docs/README.template.md` and `results/*.json` (CLAUDE.md section 2).

The template holds the prose. Every number in the parts of the README that report this
milestone is a placeholder that is looked up here, so none is typed by hand:

- `{{FILE.path.to.value}}` reads `results/FILE.json` (floats print with four decimals, `null`
  as `n/a`, booleans as yes/no);
- `{{block:NAME}}` inserts a table rendered by `scripts/render_results.py` or built below.

Usage: `python scripts/render_readme.py` writes README.md; `--check` fails if it is out of date.
"""

import argparse
import json
import re
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

from render_results import load_results, render_report

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
TEMPLATE = ROOT / "docs" / "README.template.md"
README = ROOT / "README.md"
PLACEHOLDER = re.compile(r"\{\{([^{}]+)\}\}")
GENERATED = (
    "<!-- Generated by scripts/render_readme.py from docs/README.template.md and results/. -->\n"
)


def load_json(stem: str) -> Any:  # noqa: ANN401 - arbitrary JSON
    return json.loads((RESULTS / f"{stem}.json").read_text(encoding="utf-8"))


def fmt(value: object) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def lookup(expression: str) -> str:
    stem, *path = expression.split(".")
    node = load_json(stem)
    for key in path:
        node = node[int(key)] if isinstance(node, list) else node[key]
    return fmt(node)


def refusals(stem: str, unanswerable: bool) -> str:
    queries = load_json(stem)["queries"]
    chosen = [q for q in queries if q["unanswerable"] is unanswerable]
    refused = sum(1 for q in chosen if q["outcome"] != "answered")
    return f"{refused}/{len(chosen)}"


def mutation_table() -> str:
    data = load_json("mutation")
    rows = ["| Module | Mutants | Killed | Survived |", "|---|---|---|---|"]
    for name, row in data["files"].items():
        rows.append(f"| `{name}` | {row['mutants']} | {row['killed']} | {len(row['survivors'])} |")
    rows.append(
        f"| total | {data['mutants']} | {data['killed']} | {data['mutants'] - data['killed']} |"
    )
    survivors = [
        f"- `{name}` line {s['line']}: {s['change']}"
        for name, row in data["files"].items()
        for s in row["survivors"]
    ]
    return "\n".join(rows + (["", *survivors] if survivors else []))


BLOCKS: dict[str, Callable[[], str]] = {
    "retrieval_test": lambda: render_report(load_results(RESULTS / "retrieval_test_M5.json"), None),
    "generation_test": lambda: render_report(
        load_results(RESULTS / "generation_test_M6.json"), None
    ),
    "test_refused_answerable": lambda: refusals("generation_test_M6", False),
    "test_refused_unanswerable": lambda: refusals("generation_test_M6", True),
    "test_unanswerable_total": lambda: refusals("generation_test_M6", True).split("/")[1],
    "mutation": mutation_table,
}


def substitute(match: re.Match[str]) -> str:
    expression = match.group(1).strip()
    if expression.startswith("block:"):
        return BLOCKS[expression.removeprefix("block:")]().strip()
    return lookup(expression)


def render() -> str:
    return GENERATED + PLACEHOLDER.sub(substitute, TEMPLATE.read_text(encoding="utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    text = render()
    if parser.parse_args().check:
        if README.read_text(encoding="utf-8") != text:
            print("README.md is out of date; run `make readme`", file=sys.stderr)
            return 1
        return 0
    README.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
